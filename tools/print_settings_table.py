"""Render the README's print-settings tables from the release 3MF, so the README states exactly what the 3MF slices with.

Reads Metadata/project_settings.config (the profile) and Metadata/model_settings.config (per-object overrides) and writes two Markdown tables, per
part and shared, between the README markers. Standard library only, so CI can run it without the build toolchain.
Usage: python3 tools/print_settings_table.py          rewrite the README section
       python3 tools/print_settings_table.py --check  exit 1 if the README section differs from the 3MF
Check limit: this proves the README agrees with the 3MF's stored settings, not that the slicer applies them; the per-object overrides were
confirmed separately by slicing with and without them (issue #6). Hand-edits between the markers are overwritten.
"""
from __future__ import annotations

import json
import logging
import os
import re
import sys
import zipfile
from pathlib import Path
from xml.etree import ElementTree

logging.basicConfig(level=os.environ.get("EXPORT_LOG", "INFO"), format="%(asctime)s %(levelname)s %(name)s: %(message)s")
log = logging.getLogger("print_settings_table")

ROOT = Path(__file__).resolve().parent.parent
RELEASE_3MF = ROOT / "3mf" / "free_roll_x4_u1_abs.3mf"
README = ROOT / "README.md"
BEGIN = "<!-- print-settings:begin (generated by tools/print_settings_table.py from 3mf/free_roll_x4_u1_abs.3mf; do not edit) -->"
END = "<!-- print-settings:end -->"
PARTS = (   # (object name prefix in the 3MF, label in the table); the first matching prefix wins, so the stand variants share one row
    ("Stand Pi X4", "Stand"),
    ("Wedge - Single Sided", "Wedge"),
    ("Adaptive Pulley Half", "Pulley core half"),
    ("Adaptive Clip Petal", "Petal"),
)
FILAMENT_SLOT = 0   # every object prints from extruder 1, so list-valued filament settings are read from the first slot


def first(value: str | list[str]) -> str:
    """The value used by FILAMENT_SLOT for a list-valued setting, or the value itself."""
    return value[FILAMENT_SLOT] if isinstance(value, list) else value


def mm(value: str) -> str:
    """A length without trailing zeros ('8.0' -> '8')."""
    return f"{float(value):g}"


def load(path: Path) -> tuple[dict[str, str | list[str]], dict[str, dict[str, str]], dict[str, int]]:
    """Project settings, the per-object overrides by part label, and the instance count by part label."""
    with zipfile.ZipFile(path) as z:
        project = json.loads(z.read("Metadata/project_settings.config"))
        objects = ElementTree.fromstring(z.read("Metadata/model_settings.config")).iter("object")
        overrides: dict[str, dict[str, str]] = {}
        counts: dict[str, int] = {}
        for obj in objects:
            meta = {m.get("key", ""): m.get("value", "") for m in obj.findall("metadata")}
            name = meta.pop("name", "")
            extruder = meta.pop("extruder", str(FILAMENT_SLOT + 1))
            if extruder != str(FILAMENT_SLOT + 1):
                raise RuntimeError(f"{path.name}: object {name!r} prints from extruder {extruder}; the table reads filament slot {FILAMENT_SLOT + 1} only")
            label = next((lbl for prefix, lbl in PARTS if name.startswith(prefix)), None)
            if label is None:
                raise RuntimeError(f"{path.name}: object {name!r} is not one of the release parts {[p for p, _ in PARTS]}")
            if label in overrides and overrides[label] != meta:
                raise RuntimeError(f"{path.name}: copies of {label} carry different overrides: {overrides[label]} vs {meta}")
            overrides[label] = meta
            counts[label] = counts.get(label, 0) + 1
    missing = [lbl for _, lbl in PARTS if lbl not in overrides]
    if missing:
        raise RuntimeError(f"{path.name}: no objects for {missing}")
    return project, overrides, counts


def render(path: Path) -> str:
    """The generated section: per-part table, shared-settings table, and a note on where the values come from."""
    project, overrides, counts = load(path)

    def get(label: str, key: str) -> str:
        return first(overrides[label][key] if key in overrides[label] else project[key])

    rows = ["| Part | Count | Layer | Walls | Top / bottom shells | Brim | Inner walls |", "|---|---|---|---|---|---|---|"]
    for _, label in PARTS:
        brim_type = get(label, "brim_type")
        brim = {"outer_only": "outer", "auto_brim": "auto", "brim_ears": "ears", "no_brim": "none"}.get(brim_type, brim_type)
        brim = brim if brim_type == "no_brim" else f"{brim}, {mm(get(label, 'brim_width'))} mm"
        rows.append(f"| {label} | {counts[label]} | {get(label, 'layer_height')} mm | {get(label, 'wall_loops')} | {get(label, 'top_shell_layers')} / "
                    f"{get(label, 'bottom_shell_layers')} | {brim} | {get(label, 'inner_wall_speed')} mm/s, {get(label, 'inner_wall_acceleration')} mm/s² |")
    shared = [
        ("Printer", f"{project['printer_settings_id']}, Snapmaker Orca {project['version']}"),
        ("Filament", f"{first(project['filament_type'])}, nozzle {first(project['nozzle_temperature'])} °C, bed {first(project['hot_plate_temp'])} °C"),
        ("Chamber", f"{first(project['chamber_temperature'])} °C" if first(project.get("activate_chamber_temp_control", "0")) == "1" else "not controlled (the 3MF stores a target, but chamber control is off)"),
        ("First layer", f"{project['initial_layer_print_height']} mm"),
        ("Infill", f"{project['sparse_infill_pattern']} {project['sparse_infill_density']}"),
        ("Outer walls", f"{first(project['outer_wall_speed'])} mm/s, {first(project['outer_wall_acceleration'])} mm/s²"),
        ("Part cooling fan", f"{first(project['fan_min_speed'])} to {first(project['fan_max_speed'])} %"),
        ("Supports", "on" if project["enable_support"] == "1" else "off"),
        ("Prime tower", "on" if project["enable_prime_tower"] == "1" else "off"),
    ]
    table2 = ["| Shared by every part | |", "|---|---|"] + [f"| {k} | {v} |" for k, v in shared]
    note = (f"These are the settings stored in [`3mf/{path.name}`](3mf/{path.name}) (one dryer's set: two rollers, five plates), "
            f"the same per-part settings the installed parts were printed with. Open the 3MF in Snapmaker Orca {project['version']} and the per-part values are already applied.")
    return "\n".join([BEGIN, note, "", *rows, "", *table2, END])


def main(argv: list[str]) -> int:
    """Rewrite or check the README section; returns the exit code."""
    text = README.read_text()
    pattern = re.compile(re.escape(BEGIN.split(" (")[0]) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise RuntimeError(f"{README.name} has no print-settings markers")
    updated = pattern.sub(lambda _: render(RELEASE_3MF), text, count=1)
    if "--check" in argv:
        if updated != text:
            log.error("README print settings differ from %s: run python3 tools/print_settings_table.py", RELEASE_3MF.name)
            return 1
        log.info("README print settings match %s", RELEASE_3MF.name)
        return 0
    README.write_text(updated)
    log.info("wrote the print settings from %s into %s", RELEASE_3MF.name, README.name)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
